/**
 * Generate the daily-mission pool: `npx tsx scripts/dailyPool.ts [--games 700] [--games3 150] [--seed 3]`.
 * Deterministic for given arguments. Writes src/dailyPool.ts (commit the result; src/daily.test.ts proves
 * every entry). Selection: mined candidates that are not already hand-curated missions, per goal/move-budget
 * quotas, one entry per position, fewest working first moves first, at most three entries per forcing move so the pool isn't one idea.
 */
import { writeFileSync } from 'node:fs';
import { MISSIONS } from '../src/missions';
import { mine, type Candidate } from './mine';

const args = process.argv.slice(2);
const opt = (k: string, d: number) => (args.includes(k) ? Number(args[args.indexOf(k) + 1]) : d);
const games = opt('--games', 700);
const seed = opt('--seed', 3);
const games3 = opt('--games3', 150); // 3-move mining is slow, so it gets its own, smaller run

const QUOTA: Record<string, number> = {
  burn2: 16,
  extract2: 16,
  win2: 12,
  burn1: 6,
  extract1: 4,
  win1: 4,
  burn3: 4,
  extract3: 4,
  win3: 2,
};

const curated = new Set(MISSIONS.map((m) => m.state));
const buckets = new Map<string, Candidate[]>();
const seen = new Set<string>();
for (const c of [...mine(games, seed), ...mine(games3, seed, [3])]) {
  const key = `${c.goal}${c.moves}`;
  const id = `${key}|${c.state}`;
  if (curated.has(c.state) || seen.has(id) || !(key in QUOTA)) continue;
  seen.add(id);
  buckets.set(key, [...(buckets.get(key) ?? []), c]);
}

const sig = (c: Candidate) =>
  c.first.kind === 'pass' ? 'pass' : `${c.first.kind}:${c.first.to.r}${c.first.to.c}`;
const picked: Candidate[][] = [];
const usedStates = new Set<string>(); // one entry per position, whatever its goal
for (const [key, quota] of Object.entries(QUOTA)) {
  const pool = (buckets.get(key) ?? []).sort(
    (a, b) => a.sols / a.total - b.sols / b.total || a.ply - b.ply || (a.state < b.state ? -1 : 1),
  );
  const used = new Map<string, number>();
  const out: Candidate[] = [];
  for (const c of pool) {
    if (out.length >= quota) break;
    if (usedStates.has(c.state)) continue;
    const s = sig(c);
    if ((used.get(s) ?? 0) >= 3) continue;
    used.set(s, (used.get(s) ?? 0) + 1);
    usedStates.add(c.state);
    out.push(c);
  }
  console.error(`${key}: ${out.length}/${quota} (from ${pool.length} candidates)`);
  picked.push(out);
}

// Interleave the buckets so neighbouring entries differ in goal.
const lines: string[] = [];
for (let i = 0; picked.some((p) => i < p.length); i++) {
  for (const p of picked) {
    const c = p[i];
    if (c) lines.push(`  { goal: '${c.goal}', moves: ${c.moves}, state: '${c.state}' },`);
  }
}

writeFileSync(
  'src/dailyPool.ts',
  `import type { Goal } from './ai/solve';

/**
 * Daily-mission pool. GENERATED by \`npx tsx scripts/dailyPool.ts\` (games ${games}, seed ${seed}): don't edit by hand.
 * Each entry is a Red-to-move position where the goal is forced within \`moves\` Red moves and not fewer;
 * \`src/daily.test.ts\` proves every one (and its solution replay).
 */
export interface PoolEntry {
  goal: Goal;
  moves: number;
  state: string;
}

export const DAILY_POOL: readonly PoolEntry[] = [
${lines.join('\n')}
];
`,
);
console.error(`wrote src/dailyPool.ts with ${lines.length} entries`);
